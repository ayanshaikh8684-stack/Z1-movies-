package com.example.data.local.entities

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.example.data.model.Movie

@Entity(tableName = "movies")
data class MovieEntity(
    @PrimaryKey
    val id: String,
    val title: String,
    val description: String,
    val posterUrl: String,
    val backdropUrl: String,
    val videoUrl: String,
    val trailerUrl: String = "",
    val year: Int,
    val duration: String,
    val durationMinutes: Int = 115,
    val rating: Float,
    val genres: List<String>,
    val language: String,
    val director: String,
    val cast: List<String>,
    val quality: String = "4K Ultra HD",
    val subtitles: List<String> = listOf("English", "Hindi", "Urdu", "Spanish", "French"),
    val audioTracks: List<String> = listOf("English (Dolby Atmos)", "Hindi (Original 5.1)", "Urdu (Stereo)"),
    val ageRating: String = "16+",
    val isFeatured: Boolean = false,
    val isTrending: Boolean = false,
    val isNewRelease: Boolean = false,
    val isRecentlyAdded: Boolean = false,
    val isLicensedDownloadAllowed: Boolean = true,
    val colorGradientStart: Long = 0xFF1E293B,
    val colorGradientEnd: Long = 0xFF0F172A,
    val accentColor: Long = 0xFF00E5FF,
    val trendingRank: Int? = null,
    val tagline: String = "An epic cinematic journey",
    val contentLicenseStatus: String = "Licensed & Public Domain Stream",
    val isPublished: Boolean = true,
    val digitalReleaseDate: String = "",
    val rightsStartDate: Long? = null,
    val rightsExpiryDate: Long? = null,
    val publishAt: Long? = null,
    val subtitleUrl: String = "",
    val rightsProvider: String = "Authorized Studio Partner",
    val territory: String = "Global / Worldwide",
    val isStreamingPermitted: Boolean = true,
    val isDownloadPermitted: Boolean = true,
    val isAdSupportedPermitted: Boolean = true,
    val hideWhenExpired: Boolean = false,
    val isPremiumEarlyAccess: Boolean = false,
    val premiumReleaseDate: Long? = null,
    val freeReleaseDate: Long? = null,
    val autoFreeAfterDate: Boolean = true,
    val premiumOnlyDurationDays: Int = 14,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis()
) {
    fun toMovie(): Movie = Movie(
        id = id,
        title = title,
        description = description,
        posterUrl = posterUrl,
        backdropUrl = backdropUrl,
        videoUrl = videoUrl,
        trailerUrl = trailerUrl,
        year = year,
        duration = duration,
        durationMinutes = durationMinutes,
        rating = rating,
        genres = genres,
        language = language,
        director = director,
        cast = cast,
        quality = quality,
        subtitles = subtitles,
        audioTracks = audioTracks,
        ageRating = ageRating,
        isFeatured = isFeatured,
        isTrending = isTrending,
        isNewRelease = isNewRelease,
        isRecentlyAdded = isRecentlyAdded,
        isLicensedDownloadAllowed = isLicensedDownloadAllowed,
        colorGradientStart = colorGradientStart,
        colorGradientEnd = colorGradientEnd,
        accentColor = accentColor,
        trendingRank = trendingRank,
        tagline = tagline,
        contentLicenseStatus = contentLicenseStatus,
        licenseType = contentLicenseStatus,
        isPublished = isPublished,
        digitalReleaseDate = digitalReleaseDate,
        rightsStartDate = rightsStartDate,
        rightsExpiryDate = rightsExpiryDate,
        publishAt = publishAt,
        subtitleUrl = subtitleUrl,
        rightsProvider = rightsProvider,
        territory = territory,
        isStreamingPermitted = isStreamingPermitted,
        isDownloadPermitted = isDownloadPermitted,
        isAdSupportedPermitted = isAdSupportedPermitted,
        hideWhenExpired = hideWhenExpired,
        isPremiumEarlyAccess = isPremiumEarlyAccess,
        premiumReleaseDate = premiumReleaseDate,
        freeReleaseDate = freeReleaseDate,
        autoFreeAfterDate = autoFreeAfterDate,
        premiumOnlyDurationDays = premiumOnlyDurationDays,
        createdAt = createdAt,
        updatedAt = updatedAt
    )

    companion object {
        fun fromMovie(movie: Movie): MovieEntity = MovieEntity(
            id = movie.id,
            title = movie.title,
            description = movie.description,
            posterUrl = movie.posterUrl,
            backdropUrl = movie.backdropUrl,
            videoUrl = movie.videoUrl,
            trailerUrl = movie.trailerUrl,
            year = movie.year,
            duration = movie.duration,
            durationMinutes = movie.durationMinutes,
            rating = movie.rating,
            genres = movie.genres,
            language = movie.language,
            director = movie.director,
            cast = movie.cast,
            quality = movie.quality,
            subtitles = movie.subtitles,
            audioTracks = movie.audioTracks,
            ageRating = movie.ageRating,
            isFeatured = movie.isFeatured,
            isTrending = movie.isTrending,
            isNewRelease = movie.isNewRelease,
            isRecentlyAdded = movie.isRecentlyAdded,
            isLicensedDownloadAllowed = movie.isLicensedDownloadAllowed,
            colorGradientStart = movie.colorGradientStart,
            colorGradientEnd = movie.colorGradientEnd,
            accentColor = movie.accentColor,
            trendingRank = movie.trendingRank,
            tagline = movie.tagline,
            contentLicenseStatus = movie.contentLicenseStatus,
            isPublished = movie.isPublished,
            digitalReleaseDate = movie.digitalReleaseDate,
            rightsStartDate = movie.rightsStartDate,
            rightsExpiryDate = movie.rightsExpiryDate,
            publishAt = movie.publishAt,
            subtitleUrl = movie.subtitleUrl,
            rightsProvider = movie.rightsProvider,
            territory = movie.territory,
            isStreamingPermitted = movie.isStreamingPermitted,
            isDownloadPermitted = movie.isDownloadPermitted,
            isAdSupportedPermitted = movie.isAdSupportedPermitted,
            hideWhenExpired = movie.hideWhenExpired,
            isPremiumEarlyAccess = movie.isPremiumEarlyAccess,
            premiumReleaseDate = movie.premiumReleaseDate,
            freeReleaseDate = movie.freeReleaseDate,
            autoFreeAfterDate = movie.autoFreeAfterDate,
            premiumOnlyDurationDays = movie.premiumOnlyDurationDays,
            createdAt = movie.createdAt,
            updatedAt = movie.updatedAt
        )
    }
}
